"""Build manuscript/sn-manuscript/: a self-contained Springer Nature submission package.

Everything the publisher needs and nothing else: one flattened main .tex, one flattened
supplement .tex, the class and bibliography style, one .bib and the figures. All \\input
files (sections, generated prose, generated tables, generated numbers) are resolved
in place, so the package has no internal dependencies on the working tree.

The package is GENERATED: edit manuscript/sn_main.tex, manuscript/sections_sn/... and the
experiment scripts, then re-run this.
"""
import re, shutil, sys
from pathlib import Path

M = Path("manuscript")
OUT = M / "sn-manuscript"
INPUT = re.compile(r"\\input\{([^}]+)\}")


def flatten(path: Path, depth: int = 0) -> str:
    text = path.read_text()
    if depth > 8:
        raise RuntimeError("input nesting too deep: " + str(path))

    def sub(m):
        name = m.group(1)
        # The SN/CE preamble already defines every cross-reference macro with
        # \newcommand, so the \providecommand defaults carried by each generated
        # snippet are inert duplicates: drop them from the flattened package.
        if name.rstrip(".tex").endswith("refdefs"):
            return ""
        target = M / (name if name.endswith(".tex") else name + ".tex")
        if not target.exists():
            raise FileNotFoundError(target)
        return flatten(target, depth + 1).rstrip("\n")

    return INPUT.sub(sub, text)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for stale in OUT.glob("*"):
        if stale.is_file() and stale.suffix in {".aux", ".log", ".fls", ".fdb_latexmk",
                                                ".out", ".blg", ".spl", ".gz"}:
            stale.unlink()

    for src, dst in [("sn_main.tex", "main.tex"), ("supplement_sn.tex", "supplement.tex")]:
        body = flatten(M / src)
        (OUT / dst).write_text(body)
        clean = "\\input{" not in body
        print(f"flattened {src} -> sn-manuscript/{dst}: "
              f"{len(body.splitlines())} lines, fully inlined: {clean}")

    shutil.copyfile(M / "sn-jnl.cls", OUT / "sn-jnl.cls")
    shutil.copyfile(M / "sn-nature.bst", OUT / "sn-nature.bst")
    shutil.copyfile(M / "refs.bib", OUT / "refs.bib")
    # names produced by earlier versions of this script; remove if still around
    for stale_name in ("refs_sn.bib", "sn_main.tex", "supplement_sn.tex"):
        if (OUT / stale_name).exists():
            (OUT / stale_name).unlink()
    figures = OUT / "figures"
    figures.mkdir(exist_ok=True)
    used = set(re.findall(r"includegraphics\[[^\]]*\]\{figures/([^}]+)\}",
                          (OUT / "main.tex").read_text()))
    for f in sorted(figures.glob("*")):
        if f.name not in used:
            f.unlink()
    for name in sorted(used):
        shutil.copyfile(M / "figures" / name, figures / name)
    (OUT / "README.txt").write_text(
        "Springer Nature submission package (generated by "
        "experiments/make_submission_package.py -- do not edit by hand).\n\n"
        "  main.tex        manuscript, all sections and tables inlined\n"
        "  supplement.tex  Supplementary Information\n"
        "  refs.bib        bibliography, 41 entries\n"
        "  sn-jnl.cls      Springer Nature class\n"
        "  sn-nature.bst   Nature reference style, with a one-function local fix\n"
        "                  (see the comment above format.in.ed.booktitle): the file as\n"
        "                  shipped in the template aborts BibTeX on @inproceedings and\n"
        "                  @incollection entries and drops the venue\n"
        "  figures/        vector figures used by main.tex\n"
        "  main.bbl        pre-built reference list, so the package typesets even\n"
        "                  without running BibTeX\n\n"
        "Build:\n"
        "  pdflatex main && bibtex main && pdflatex main && pdflatex main\n"
        "  pdflatex supplement && pdflatex supplement\n")
    print("package files:", sorted(p.name for p in OUT.iterdir()))
    print("figures:", sorted(p.name for p in figures.iterdir()))


if __name__ == "__main__":
    main()
